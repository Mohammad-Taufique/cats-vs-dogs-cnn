
import streamlit as st
import tensorflow as tf
import numpy as np
from PIL import Image, ImageOps
from pathlib import Path

# =====================================
# 1. PAGE CONFIGURATION
# =====================================

st.set_page_config(
    page_title="Cats vs Dogs AI Classifier",
    page_icon="🐱",
    layout="centered"
)

# =====================================
# 2. LOAD TRAINED CNN MODEL
# =====================================

BASE_DIR = Path(__file__).resolve().parent

MODEL_PATH = BASE_DIR / "model" / "cats_dogs_cnn.keras"

@st.cache_resource
def load_model():
    return tf.keras.models.load_model(MODEL_PATH)

try:
    model = load_model()
except Exception as e:
    st.error(f"Model loading failed: {e}")
    st.stop()

# =====================================
# 3. PREPROCESS IMAGE
# =====================================

def preprocess_image(image):

    image = ImageOps.exif_transpose(image)
    image = image.convert("RGB")

    image = image.resize((128, 128))

    image_array = np.array(image, dtype=np.float32)

    image_array = image_array / 255.0

    image_array = np.expand_dims(image_array, axis=0)

    return image_array

# =====================================
# 4. APPLICATION UI
# =====================================

st.title("🐱 Cats vs Dogs Classifier")

st.subheader("AI-Powered Image Classification")

st.write(
    "Upload an image of a cat or dog "
    "and let our CNN model predict the category."
)

st.divider()

uploaded_file = st.file_uploader(
    "Choose an image",
    type=["jpg", "jpeg", "png"]
)

# =====================================
# 5. PREDICTION
# =====================================

if uploaded_file is not None:

    image = Image.open(uploaded_file)

    st.image(
        image,
        caption="Uploaded Image",
        use_container_width=True
    )

    if st.button("🔍 Predict Image", use_container_width=True):

        with st.spinner("AI is analyzing your image..."):

            processed_image = preprocess_image(image)

            prediction = model.predict(
                processed_image,
                verbose=0
            )

            probability = float(
                np.asarray(prediction).reshape(-1)[0]
            )

            if probability >= 0.5:
                label = "Dog 🐶"
                confidence = probability * 100
            else:
                label = "Cat 🐱"
                confidence = (1 - probability) * 100

        st.divider()

        st.success("Prediction Completed!")

        st.markdown(f"## Prediction: {label}")

        st.metric(
            "Confidence",
            f"{confidence:.2f}%"
        )

        st.progress(
            int(round(confidence))
        )

        st.caption(
            "Prediction generated by your trained CNN model."
        )

else:
    st.info("Please upload a cat or dog image to begin.")

# =====================================
# 6. FOOTER
# =====================================

st.divider()

st.caption(
    "Built using Python, TensorFlow, CNN and Streamlit."
)
